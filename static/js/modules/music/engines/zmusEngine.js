// ZMUS — Joe Zbiciak's microprogrammed music engine for the Intellivision.
//
// The engine source lives in intv-game-builder/lib/zmus_engine.bas. It decodes
// a stream of 16-bit DECLE words into per-frame PSG register writes via a
// tight CP1610 inner loop that uses SARC (shift-arithmetic-right-with-carry)
// to walk a per-tick bitmap of "which PSG registers to write this frame".
//
// ── Phase 1 (this file) ─────────────────────────────────────────────────────
// Opaque-container support: parse a NUTMARCH-style PROC block, extract the
// stream of DECLE words, hold them on song.metadata.zmusBytes, and emit them
// back unchanged on serialize. The song shows up in the editor with byte-
// count + DECLE preview, round-trips losslessly, and slots into the engine
// selector so users can identify and manage ZMUS files inside the studio.
//
// What Phase 1 INTENTIONALLY does not do:
//   • Decode the bitstream into musical notes (no piano-roll, no playback)
//   • Allow compose/edit operations (the SongIR's `notes` array stays empty)
//   • Convert to/from IntyBASIC MUSIC (different abstraction tier)
//
// ── Phase 2 (deferred) ──────────────────────────────────────────────────────
// Build a CP1610 micro-simulator that runs ZMUS_UPDATE one frame at a time
// against the data stream, capturing PSG register writes per frame. From
// those writes, reconstruct musical notes (period → MIDI, channel from
// register address, duration from how long the period holds). Once decoded
// the song renders on the piano-roll and plays via Web Audio.
//
// The reverse-engineering effort is substantial — a one-shot static analysis
// is error-prone, but a simulator that mirrors ~12 specific CP1610 ops
// (MVI/MVO/SARC/SLLC/INCR/SLR/SLL/ADDR/XORR/ANDI/TSTR/BEQ/B) reliably
// produces the same PSG trace the real engine would. That's the right way.

import { MusicEngine } from './engineBase.js';

// Match an ASM PROC block. Songs in the wild are wrapped in IntyBASIC ASM
// statements (the `ASM` prefix on each line), so we accept both forms.
// /m flag — songs typically open with a comment header, so the PROC line
// is several lines into the file and `^` needs per-line matching.
const PROC_START_RE = /^(?:ASM\s+)?([A-Z_][A-Z0-9_]*)\s*:\s*PROC\b/im;
const PROC_END_RE   = /^(?:ASM\s+)?ENDP\b/i;
// DECLE line, with optional ASM prefix. Captures the comma-separated values.
const DECLE_RE = /^(?:ASM\s+)?DECLE\s+(.+?)(?:\s*;.*)?$/i;

export class ZmusEngine extends MusicEngine {
    static formatName    = 'ZMUS (Zbiciak microprogrammed)';
    static formatSlug    = 'zmus';
    static channelCount  = 3;
    static supportsDrums = false;   // ZMUS is 3 tone channels; no noise/drum slot

    /** Sniff to help the auto-detect path in musicEditor pick this engine. */
    static looksLike(text) {
        // Strong signal: an ASM PROC block + a long run of DECLE $XXXX lines
        if (!PROC_START_RE.test(text)) return false;
        const decleCount = (text.match(/DECLE\s+\$[0-9A-F]/gi) || []).length;
        return decleCount >= 8;
    }

    static parse(text) {
        const lines = text.replace(/\r/g, '').split('\n');
        let procName = null;
        let inProc = false;
        const decles = [];

        for (const line of lines) {
            if (!inProc) {
                const m = line.match(PROC_START_RE);
                if (m) { procName = m[1]; inProc = true; }
                continue;
            }
            if (PROC_END_RE.test(line)) { inProc = false; continue; }
            const m = line.match(DECLE_RE);
            if (!m) continue;
            for (const tok of m[1].split(',').map(s => s.trim()).filter(Boolean)) {
                const v = this._evalDecleToken(tok);
                if (v != null) decles.push(v & 0xFFFF);
            }
        }

        if (!procName || decles.length === 0) {
            throw new Error('No ZMUS song PROC found. Expected "NAME PROC ... DECLE $XXXX ... ENDP" block.');
        }

        const song = this.defaultSong();
        song.label = procName;
        song.metadata.zmusBytes = decles;             // canonical opaque payload
        song.metadata.zmusByteCount = decles.length * 2; // 1 DECLE = 2 ROM bytes
        return song;
    }

    static serialize(song) {
        const decles = song?.metadata?.zmusBytes || [];
        if (decles.length === 0) {
            return [
                "' Empty ZMUS song — open this in the editor's ZMUS engine,",
                "' import an existing song from intv-game-builder/assets/music/,",
                "' or wait for Phase 2 (bytecode editor) to compose one from scratch.",
            ].join('\n');
        }
        const label = song.label || 'untitled_zmus';
        const lines = [
            `' Generated by Intellivision Overlay Editor`,
            `' ZMUS song — pass through INCLUDE "lib/zmus_engine.bas" and call`,
            `' USR ZMUS_PLAY(${label})  to play. Round-tripped from the editor without decode.`,
            ``,
            `ASM ${label}:   PROC`,
        ];
        // 6 DECLEs per line keeps the source readable and matches the
        // convention used by the Nutcracker sample on disk.
        const PER_LINE = 6;
        for (let i = 0; i < decles.length; i += PER_LINE) {
            const chunk = decles.slice(i, i + PER_LINE)
                .map(v => `$${v.toString(16).toUpperCase().padStart(4, '0')}`)
                .join(', ');
            lines.push(`ASM         DECLE   ${chunk}`);
        }
        lines.push(`ASM         ENDP`);
        return lines.join('\n');
    }

    static defaultSong() {
        return {
            engine:       this.formatSlug,
            label:        'new_zmus_song',
            ticksPerNote: 1,                 // ZMUS is per-frame; no fixed step
            channelCount: 3,
            notes:        [],
            controls:     [],
            metadata: {
                zmusBytes:     [],
                zmusByteCount: 0,
                placeholder:   true,
            },
        };
    }

    // ── SongIR helpers shared with the editor ──────────────────────────────

    static getTotalTicks(_song) {
        // Phase 1 has no decoded note timeline; the piano-roll falls back to
        // its empty-state hint. Phase 2 will return actual decoded ticks.
        return 0;
    }

    static getLoopInfo(_song) {
        return null;   // Phase 2 will detect end-of-song link words
    }

    static getPlaybackTicks(song, _loopCount = 4) {
        return this.getTotalTicks(song);
    }

    static tempoAt(_song, _tick) {
        return 1;   // microprogram ticks at frame rate (60 Hz on NTSC)
    }

    static estimateRomBytes(song) {
        return song?.metadata?.zmusByteCount || 0;
    }

    static toPlaybackEvents(_song, _framerate = 50, _loopCount = 4) {
        // Phase 2 will simulate the engine and emit note events from PSG writes
        return [];
    }

    // ── DECLE expression eval (subset; only what shows up in song data) ────

    static _evalDecleToken(tok) {
        const t = tok.trim();
        if (t === '') return null;
        if (/^\$[0-9a-f]+$/i.test(t)) return parseInt(t.slice(1), 16);
        if (/^0x[0-9a-f]+$/i.test(t)) return parseInt(t.slice(2), 16);
        if (/^-?\d+$/.test(t))         return parseInt(t, 10) & 0xFFFF;
        // Label references and arithmetic expressions in song data are rare;
        // when present we record 0 and rely on the round-trip preserving the
        // ORIGINAL source text rather than the decoded values. The editor's
        // typical use is round-tripping pre-built songs, so this is OK.
        return 0;
    }
}
